import os, sys, json
from playwright.sync_api import sync_playwright
src, out = sys.argv[1], sys.argv[2]
html = open(src, encoding="utf-8").read()
wrapped = ('<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
           '<style>[hidden]{display:none!important}body{margin:0}img{max-width:100%}</style></head><body>' + html + '</body></html>')
path = os.path.abspath(out + '-page.html'); open(path, 'w', encoding='utf-8').write(wrapped)
ROUTES = ['home', 'assumable', 'zero-down', 'payment', 'new-builds', 'placer', 'stockton', 'refinance', 'build', 'about', 'alerts', 'finder', 'cart']
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={"width": 1280, "height": 900}, reduced_motion="reduce")
    pg = ctx.new_page(); errs = []
    pg.on("pageerror", lambda e: errs.append("pageerror: " + str(e)))
    pg.on("console", lambda m: errs.append(m.text) if m.type == "error" and "net::" not in m.text and "Failed to load" not in m.text else None)
    pg.route("http*://**", lambda r: r.abort())
    pg.goto("file://" + path + "#for-maria-lopez"); pg.wait_for_timeout(400)
    q = pg.evaluate
    print("start:", q("document.documentElement.dataset.page"), "| client chip:", q("(document.querySelector('.forwho')||{}).textContent"), "| errors:", errs)
    for r in ROUTES:
        q(f"location.hash = '{r}'"); pg.wait_for_timeout(120)
        info = q("({h1: document.getElementById('page-title').textContent, cards: document.querySelectorAll('#view .card').length, tiles: document.querySelectorAll('#view .tile').length, sw: document.documentElement.scrollWidth, count: (document.querySelector('#view .count')||{}).textContent || '', big: [...document.querySelectorAll('#view .big')].map(x=>x.textContent).join(' | ')})")
        print(f"{r:11s}", json.dumps(info)[:260])
    print("route errors:", errs)
    # search
    q("location.hash = 'home'"); pg.wait_for_timeout(100)
    pg.fill('#q', 'Loomis'); pg.wait_for_timeout(80)
    print("search Loomis:", q("[...document.querySelectorAll('#q-sugg button')].map(b=>b.textContent).join(' / ')")[:300])
    pg.press('#q', 'ArrowDown'); pg.press('#q', 'Enter'); pg.wait_for_timeout(150)
    print(" -> page:", q("document.documentElement.dataset.page"), "| count:", q("(document.querySelector('#view .count')||{}).textContent"))
    pg.fill('#q', '95212'); pg.wait_for_timeout(80)
    print("search 95212:", q("[...document.querySelectorAll('#q-sugg button')].slice(0,3).map(b=>b.textContent).join(' / ')"))
    pg.fill('#q', 'river islands'); pg.wait_for_timeout(80)
    print("search river islands:", q("[...document.querySelectorAll('#q-sugg button')].map(b=>b.textContent).join(' / ')")[:300])
    pg.press('#q', 'Enter'); pg.wait_for_timeout(150)
    print(" -> page:", q("document.documentElement.dataset.page"), "| count:", q("(document.querySelector('#view .count')||{}).textContent"))
    pg.fill('#q', 'refinance'); pg.wait_for_timeout(80); pg.press('#q', 'Enter'); pg.wait_for_timeout(150)
    print("search refinance ->", q("document.documentElement.dataset.page"))
    # gate (fallback modal)
    q("location.hash = 'assumable'"); pg.wait_for_timeout(150)
    pg.click('#view [data-gate]'); pg.wait_for_timeout(80)
    print("gate modal open:", q("!document.getElementById('modal').hidden"), "|", q("document.getElementById('modal-title').textContent"))
    pg.click('#gate-form button[type=submit]'); pg.wait_for_timeout(50)
    print(" empty submit ->", q("document.getElementById('g-err').textContent"))
    pg.fill('#g-name', 'Maria Lopez'); pg.fill('#g-phone', '209-555-0101'); pg.fill('#g-email', 'maria@example.com'); pg.click('#gate-form button[type=submit]'); pg.wait_for_timeout(80)
    print(" done:", q("document.getElementById('g-thanks').textContent"), "| options:", q("[...document.querySelectorAll('#g-opts a, #g-opts button')].map(a=>a.textContent).join(' / ')"))
    pg.keyboard.press('Escape'); pg.wait_for_timeout(50)
    # place chooser + filters
    pg.click('#kw [data-place="Stockton"]'); pg.wait_for_timeout(80)
    print("place chooser:", q("[...document.querySelectorAll('#dialog [data-pick]')].map(b=>b.textContent).join(' / ')"))
    pg.click('#dialog [data-pick="new-builds"]'); pg.wait_for_timeout(150)
    print(" -> new builds in Stockton:", q("document.getElementById('nb-count').textContent"))
    pg.select_option('#nb-loan', 'va'); pg.wait_for_timeout(60)
    print(" VA first card:", q("[...document.querySelectorAll('#nb-list .card')[0].querySelectorAll('.stats3 b')].map(b=>b.textContent).join(' / ')"))
    q("location.hash = 'payment'"); pg.wait_for_timeout(150)
    pg.select_option('#py-county', 'Placer'); pg.wait_for_timeout(80)
    print("payment Placer:", q("document.getElementById('py-max').textContent"), "|", q("document.getElementById('py-note').textContent")[:120], "|", q("[...document.querySelectorAll('#py-groups .panel b')].map(b=>b.textContent).join(' / ')")[:200])
    pg.select_option('#py-loan', 'va'); pg.wait_for_timeout(80)
    print(" VA:", q("document.getElementById('py-max').textContent"))
    q("location.hash = 'zero-down'"); pg.wait_for_timeout(150)
    pg.click('[data-zc="Stanislaus"]'); pg.wait_for_timeout(80)
    print("zero-down Stanislaus:", q("document.getElementById('zd-nb-h').textContent"), "|", q("[...document.querySelectorAll('#zd-compare b')].map(b=>b.textContent).join(' / ')"))
    q("location.hash = 'refinance'"); pg.wait_for_timeout(150)
    print("refi:", q("document.getElementById('rf-new-pi').textContent"), "|", q("document.querySelectorAll('#rf-opts .hit').length"), "hits")
    pg.select_option('#rf-type', 'va'); pg.fill('#rf-rate', '7.9'); pg.wait_for_timeout(80)
    print(" VA at 7.9%:", q("[...document.querySelectorAll('#rf-opts .hit h3')].map(h=>h.textContent).join(', ')"), "|", q("document.getElementById('rf-new-pi').textContent"))
    q("location.hash = 'build'"); pg.wait_for_timeout(150)
    print("build:", q("document.getElementById('bd-total').textContent"), "|", q("document.getElementById('bd-note').textContent")[:140])
    q("location.hash = 'alerts'"); pg.wait_for_timeout(150)
    print("alerts saved tags:", q("document.getElementById('al-saved').textContent")[:80])
    print("alerts msg:", q("document.getElementById('al-msg').value")[:260].replace('\n', ' | '))
    print("late errors:", errs)
    # screenshots: one look
    q("location.hash = 'home'"); pg.wait_for_timeout(150); q("window.scrollTo(0,0)")
    pg.screenshot(path=out + '-home.png', full_page=False)
    q("location.hash = 'new-builds'"); pg.wait_for_timeout(150); q("window.scrollTo(0,0)")
    pg.screenshot(path=out + '-newbuilds.png', clip={"x": 0, "y": 0, "width": 1280, "height": 1500}, full_page=True)
    ctx.close()
    ctx2 = b.new_context(viewport={"width": 400, "height": 1700}, color_scheme="dark", reduced_motion="reduce")
    pg2 = ctx2.new_page(); errs2 = []
    pg2.on("pageerror", lambda e: errs2.append(str(e)))
    pg2.route("http*://**", lambda r: r.abort())
    pg2.goto("file://" + path + "#assumable"); pg2.wait_for_timeout(300)
    print("phone assumable sw:", pg2.evaluate("document.documentElement.scrollWidth"), "| errors:", errs2)
    pg2.screenshot(path=out + '-phone.png')
    sws = {}
    for r in ROUTES:
        pg2.evaluate(f"location.hash = '{r}'"); pg2.wait_for_timeout(100)
        sws[r] = pg2.evaluate("document.documentElement.scrollWidth")
    print("phone widths:", sws, "| errors:", errs2)
    ctx2.close(); b.close()
